export type MessageKey = keyof typeof messages.ar;
@Injectable({ providedIn: 'root' })
export class I18n {
  private document = inject(DOCUMENT);
  readonly language = signal<'ar' | 'en'>('ar');
  constructor() {
    let saved: string | null = null;
    try {
      saved = localStorage.getItem('erp.language');
    } catch {
      /* storage is optional */
    }
    this.set(saved === 'en' ? 'en' : 'ar');
  }
  t(key: MessageKey): string {
    return messages[this.language()][key];
  }
  toggle(): void {
    this.set(this.language() === 'ar' ? 'en' : 'ar');
  }
  set(language: 'ar' | 'en'): void {
    this.language.set(language);
    this.document.documentElement.lang = language;
    this.document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    try {
      localStorage.setItem('erp.language', language);
    } catch {
      /* do not block rendering */
    }
  }
}
